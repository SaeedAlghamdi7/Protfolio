const titleKeys = {
  Home: "home",
  Work: "work",
  Services: "services",
  About: "about",
  Process: "process",
  Contact: "contact"
};

let lang = localStorage.getItem("saeed-lang") || "ar";
let booted = false;

function applyLang() {
  const dict = translations[lang];
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
  document.body.dir = lang === "ar" ? "rtl" : "ltr";

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.dataset.i18n;
    if (dict[key]) el.innerHTML = dict[key];
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    const key = el.dataset.i18nPlaceholder;
    if (dict[key]) el.placeholder = dict[key];
  });

  document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
    const key = el.dataset.i18nAria;
    if (dict[key]) el.setAttribute("aria-label", dict[key]);
  });

  document.querySelectorAll("[data-lang-toggle]").forEach((el) => {
    el.textContent = lang === "ar" ? "EN" : "عربي";
    el.setAttribute("aria-label", lang === "ar" ? "Switch to English" : "التبديل إلى العربية");
  });

  syncMenuLabel();

  const titleKey = titleKeys[document.body.dataset.title];
  document.title = (dict[titleKey] || "Portfolio") + " | Saeed Alghamdi";

  const status = document.getElementById("lang-status");
  if (booted && status) {
    status.textContent = lang === "ar" ? "تم التبديل إلى العربية" : "Switched to English";
  }
  booted = true;
}

function syncMenuLabel() {
  document.querySelectorAll(".menu-btn").forEach((btn) => {
    const open = btn.getAttribute("aria-expanded") === "true";
    btn.setAttribute("aria-label", translations[lang][open ? "menuClose" : "menuOpen"]);
  });
}

function setMenu(open) {
  const nav = document.querySelector(".navlinks");
  const btn = document.querySelector(".menu-btn");
  if (!nav || !btn) return;
  nav.classList.toggle("open", open);
  btn.setAttribute("aria-expanded", open ? "true" : "false");
  document.body.classList.toggle("menu-open", open);
  syncMenuLabel();
}

document.querySelectorAll("[data-lang-toggle]").forEach((el) => {
  el.addEventListener("click", () => {
    lang = lang === "ar" ? "en" : "ar";
    localStorage.setItem("saeed-lang", lang);
    applyLang();
  });
});

const menuBtn = document.querySelector(".menu-btn");
if (menuBtn) {
  menuBtn.addEventListener("click", () => {
    const open = menuBtn.getAttribute("aria-expanded") === "true";
    setMenu(!open);
  });
}

document.addEventListener("click", (event) => {
  const nav = document.querySelector(".navlinks");
  if (!nav || !nav.classList.contains("open")) return;
  if (nav.contains(event.target) || menuBtn.contains(event.target)) return;
  setMenu(false);
});

document.addEventListener("keydown", (event) => {
  if (event.key === "Escape") setMenu(false);
});

window.addEventListener("resize", () => {
  if (window.innerWidth > 1040) setMenu(false);
});

const page = location.pathname.split("/").pop() || "index.html";
document.querySelectorAll(".navlinks a").forEach((link) => {
  const href = link.getAttribute("href");
  const active = href === page || (page === "" && href === "index.html");
  link.classList.toggle("active", active);
  if (active) link.setAttribute("aria-current", "page");
});

applyLang();

const filters = document.querySelectorAll("[data-filter]");
const cards = document.querySelectorAll("[data-category]");
const empty = document.querySelector(".filter-empty");

filters.forEach((btn) => {
  btn.addEventListener("click", () => {
    filters.forEach((item) => {
      item.classList.remove("active");
      item.setAttribute("aria-pressed", "false");
    });
    btn.classList.add("active");
    btn.setAttribute("aria-pressed", "true");
    const selected = btn.dataset.filter;
    let visible = 0;
    cards.forEach((card) => {
      const show = selected === "all" || card.dataset.category === selected;
      card.hidden = !show;
      if (show) visible += 1;
    });
    if (empty) empty.hidden = visible !== 0;
  });
});

